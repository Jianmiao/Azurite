using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.Linq;
using System.Text.Json;

namespace Azurite.Core;

public enum AuthoringBatchMultilineMode { PerAnchorReadable, Narration, Dialogue }
public sealed record AuthoringBatchMultilineOptions(AuthoringBatchMultilineMode Mode = AuthoringBatchMultilineMode.PerAnchorReadable,
    int? SpeakerSlot = null, string? OffstageResourceId = null);
public sealed record AuthoringBatchMultilineAnchor(string StableId, string Mode, int? SpeakerSlot = null, string? OffstageResourceId = null);
public sealed record AuthoringBatchInsertedLine(string Alias, string AnchorId, int SourceIndex, int TargetIndex, int LineOffset,
    string Text, string Mode, int? SpeakerSlot, string? OffstageResourceId);

/// <summary>Logical aliases describe this batch only. Native persistent IDs are generated by Create.</summary>
public sealed class AuthoringBatchMultilinePlan
{
    internal AuthoringBatchMultilinePlan(AuthoringBatchSelection selection, string sourceText,
        IEnumerable<AuthoringBatchMultilineAnchor> anchors, IEnumerable<AuthoringBatchInsertedLine> lines, string json)
    {
        Selection = selection; SourceText = sourceText; OperationsJson = json;
        Anchors = new ReadOnlyCollection<AuthoringBatchMultilineAnchor>(anchors.ToArray());
        Lines = new ReadOnlyCollection<AuthoringBatchInsertedLine>(lines.ToArray());
    }
    public AuthoringBatchSelection Selection { get; }
    public string SourceText { get; }
    public IReadOnlyList<AuthoringBatchMultilineAnchor> Anchors { get; }
    public IReadOnlyList<AuthoringBatchInsertedLine> Lines { get; }
    public string OperationsJson { get; }
    public int OperationCount => Lines.Count;
}

public sealed record AuthoringBatchMultilinePlanResult(bool IsValid, AuthoringBatchMultilinePlan? Plan,
    AuthoringBatchNativeFailure Failure, AuthoringBatchFailure LogicalFailure, string Message);

public static class AuthoringBatchMultilineCompiler
{
    public static AuthoringBatchMultilinePlanResult TryCompile(AuthoringBatchSelection? selection, string? text,
        IReadOnlyList<AuthoringBatchMultilineAnchor>? anchors)
    {
        if (selection != null && selection.Rows.Count > 0 && !string.IsNullOrEmpty(text))
        {
            if (!AuthoringBatchPlanner.FitsMultilineLimit(text!, selection.Rows.Count, AuthoringBatchPlanner.MaxOperations, out _))
                return Fail(AuthoringBatchFailure.TooManyOperations, "Logical multiline expansion exceeds 1024 operations.");
            if (!AuthoringBatchPlanner.FitsMultilineLimit(text!, selection.Rows.Count, AuthoringBatchNativeCompiler.MaxNativeOperations, out _))
                return new(false, null, AuthoringBatchNativeFailure.NativeOperationLimit, AuthoringBatchFailure.None,
                    "Native Apply accepts at most 500 inserted lines; this batch is never split.");
        }
        var logical = AuthoringBatchPlanner.TryPlan(selection, AuthoringBatchAction.AddMultiline, text);
        if (!logical.IsValid) return Fail(logical.Failure, logical.Message);
        if (anchors == null || anchors.Count != selection!.Rows.Count)
            return Fail(AuthoringBatchFailure.InvalidSelection, "Every original anchor requires an explicit new-line mode and speaker.");
        if (!ValidUnicode(selection.NodeId) || !ValidUnicode(text!)) return UnicodeFailure();
        for (int i = 0; i < anchors.Count; i++)
        {
            var anchor = anchors[i];
            if (anchor == null || anchor.StableId != selection.Rows[i].StableId)
                return Fail(AuthoringBatchFailure.InvalidSelection, "Mode/speaker anchors differ from the ordered original selection.");
            if (!ValidUnicode(anchor.StableId) || anchor.OffstageResourceId != null && !ValidUnicode(anchor.OffstageResourceId)) return UnicodeFailure();
            bool validSpeaker = anchor.Mode == "narration" ? anchor.SpeakerSlot == null && anchor.OffstageResourceId == null
                : anchor.Mode == "dialogue" && (anchor.SpeakerSlot is >= 1 and <= 5 && anchor.OffstageResourceId == null ||
                    anchor.SpeakerSlot == null && !string.IsNullOrWhiteSpace(anchor.OffstageResourceId));
            if (!validSpeaker) return Fail(AuthoringBatchFailure.InvalidSpeaker, "New lines require explicit readable narration or a valid dialogue speaker.");
        }
        int perAnchor = logical.Plan!.Edits.Count / anchors.Count;
        var lines = new List<AuthoringBatchInsertedLine>(logical.Plan.Edits.Count);
        var operations = new List<object>(logical.Plan.Edits.Count);
        for (int i = 0; i < logical.Plan.Edits.Count; i++)
        {
            var edit = logical.Plan.Edits[i]; var anchor = anchors[i / perAnchor]; int offset = i % perAnchor;
            string alias = "multiline_" + (i + 1);
            object? speaker = anchor.SpeakerSlot != null ? new { slot = anchor.SpeakerSlot.Value }
                : anchor.OffstageResourceId != null ? new { offstage_resource_id = anchor.OffstageResourceId } : null;
            object after = offset == 0 ? new { id = anchor.StableId } : new { @ref = lines[i - 1].Alias };
            operations.Add(new { op = "line.insert", node = new { id = selection.NodeId }, @ref = alias, after_line = after,
                line = new { inherit = "previous", mode = anchor.Mode, speaker, text = edit.Text } });
            lines.Add(new(alias, anchor.StableId, edit.SourceIndex, edit.TargetIndex, offset, edit.Text!, anchor.Mode, anchor.SpeakerSlot, anchor.OffstageResourceId));
        }
        return new(true, new(selection, text!, anchors, lines, JsonSerializer.Serialize(operations)),
            AuthoringBatchNativeFailure.None, AuthoringBatchFailure.None, string.Empty);
    }

    private static AuthoringBatchMultilinePlanResult Fail(AuthoringBatchFailure failure, string message)
        => new(false, null, AuthoringBatchNativeFailure.LogicalPlanRejected, failure, message);
    private static AuthoringBatchMultilinePlanResult UnicodeFailure()
        => new(false, null, AuthoringBatchNativeFailure.InvalidUnicode, AuthoringBatchFailure.None, "Text or identity contains invalid UTF-16.");
    private static bool ValidUnicode(string value)
    {
        for (int i = 0; i < value.Length; i++)
            if (char.IsSurrogate(value[i]) && (!char.IsHighSurrogate(value[i]) || ++i >= value.Length || !char.IsLowSurrogate(value[i]))) return false;
        return true;
    }
}
